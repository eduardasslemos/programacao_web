let a: number = 10;
let b: number = 5;

console.log("Soma: ", a + b);
console.log("Subtração: ", a - b);
console.log("Divisão: ", a / b);
console.log("Módulo: ", a % b);
console.log("Multiplicação: ", a * b);
console.log("Exponenciação: ", a ** b);
//operador == compara os valores, convertendo tipos se necessário
console.log("Igualdade: ", a == b);
/*o operador === compara tanto os valores
quanto os tipos, garantindo igualdade estrita*/
console.log("Igualdade estrita: ", a === b);
a++; //a+1
console.log ("Incremento: ", a);
a += b; // a = a + b
console.log ("Atribuição com adição: ", a);